// scripts/generate-nft-art.mjs
// Generates low-resolution WebP thumbnails for every image in public/nft-images/
// and writes a manifest (src/data/nftArt.ts) used by the app.
//
// Usage:  npm run gen:art
//
// How token IDs are assigned:
//   Every image in public/nft-images/ (non-recursive) is sorted by filename
//   (numeric-aware). The Nth file in that order becomes token #N (1-based).
//   -> Adding/renaming files changes IDs, so treat the folder as append-only
//      once the collection is live.
//
// Output:
//   public/nft-images/thumbs/nft-001.webp ... (400px wide, ~85-90% smaller)
//   src/data/nftArt.ts                        (auto-generated manifest)

import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'public', 'nft-images');
const THUMB_DIR = path.join(SRC_DIR, 'thumbs');
const MANIFEST = path.join(ROOT, 'src', 'data', 'nftArt.ts');

const THUMB_WIDTH = 400;
const THUMB_QUALITY = 72;
const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);

/** Turn an AI-generated filename into a human-readable NFT name. */
function prettifyName(filename) {
  const base = filename.replace(/\.[^.]+$/, '');
  return base
    // strip trailing AI-generation timestamps like _20261013000602 (optionally _2/_3)
    .replace(/_+\d{14}(_\d+)?$/, '')
    // strip literal ellipsis characters left by truncated filenames
    .replace(/…/g, ' ')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

async function main() {
  const entries = await readdir(SRC_DIR, { withFileTypes: true });
  const files = entries
    .filter((e) => e.isFile() && IMAGE_EXTENSIONS.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }));

  if (files.length === 0) {
    console.error(`No images found in ${SRC_DIR}`);
    process.exit(1);
  }

  await mkdir(THUMB_DIR, { recursive: true });

  const art = [];
  let totalFull = 0;
  let totalThumb = 0;

  for (let i = 0; i < files.length; i++) {
    const file = files[i];
    const id = i + 1;
    const idPad = String(id).padStart(3, '0');
    const fullPath = path.join(SRC_DIR, file);
    const thumbName = `nft-${idPad}.webp`;
    const thumbPath = path.join(THUMB_DIR, thumbName);

    const fullStat = await stat(fullPath);
    totalFull += fullStat.size;

    // Skip regeneration when the thumbnail is already newer than the source
    let needsWrite = true;
    try {
      const thumbStat = await stat(thumbPath);
      needsWrite = thumbStat.mtimeMs < fullStat.mtimeMs;
    } catch {
      needsWrite = true;
    }

    if (needsWrite) {
      await sharp(fullPath)
        .rotate() // respect EXIF orientation
        .resize(THUMB_WIDTH, THUMB_WIDTH, { fit: 'cover', position: 'centre' })
        .webp({ quality: THUMB_QUALITY })
        .toFile(thumbPath);
    }
    totalThumb += (await stat(thumbPath)).size;

    art.push({
      id,
      name: prettifyName(file),
      full: `/nft-images/${encodeURIComponent(file)}`,
      thumb: `/nft-images/thumbs/${thumbName}`,
    });

    process.stdout.write(`\r[${id}/${files.length}] generating thumbnails...`);
  }

  const header = `// AUTO-GENERATED by scripts/generate-nft-art.mjs — do not edit by hand.
// Run \`npm run gen:art\` after adding/renaming images in public/nft-images/.
// Token #N corresponds to the Nth image (numeric-aware filename sort).

export interface NftArtEntry {
  id: number;
  name: string;
  full: string;
  thumb: string;
}

export const NFT_ART: NftArtEntry[] = ${JSON.stringify(art, null, 2)};
`;
  await writeFile(MANIFEST, header, 'utf8');

  const pct = totalFull > 0 ? Math.round((1 - totalThumb / totalFull) * 100) : 0;
  console.log(`\n\nDone.`);
  console.log(`  Images processed : ${files.length}`);
  console.log(`  Originals        : ${(totalFull / 1024 / 1024).toFixed(1)} MB`);
  console.log(`  Thumbnails (WebP): ${(totalThumb / 1024 / 1024).toFixed(1)} MB (${pct}% smaller)`);
  console.log(`  Manifest         : ${path.relative(ROOT, MANIFEST)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
